package depsconf

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"

	"nekpo/internal/proto"
)

const (
	ConfName = "deps.conf"
	LockName = "deps.lock"
)

type Dep struct {
	Lang    string
	Name    string
	Version string
	Arch    string
}

func (d Dep) Key() string { return d.Lang + "/" + d.Arch + "/" + d.Name }

func (d Dep) String() string {
	v := d.Version
	if v == "" {
		v = "latest"
	}
	return fmt.Sprintf("%s:%s (%s, %s)", d.Name, v, d.Lang, d.Arch)
}

type File struct {
	Server string
	Deps   []Dep
}

type LockEntry struct {
	Dep
	SHA256 string
}

type Lock struct {
	Entries []LockEntry
}

func cut(line string) string {
	if i := strings.Index(line, "#"); i >= 0 {
		line = line[:i]
	}
	return strings.TrimSpace(line)
}

func ParseDep(lang, spec, arch string) (Dep, error) {
	name, version, _ := strings.Cut(spec, ":")
	d := Dep{Lang: lang, Name: name, Version: version, Arch: proto.NormalizeArch(arch)}
	if err := proto.ValidDepKey(d.Lang, d.Arch, d.Name); err != nil {
		return d, err
	}
	if d.Version != "" && !proto.DepVersionRe.MatchString(d.Version) {
		return d, fmt.Errorf("invalid version %q", d.Version)
	}
	if d.Version == "latest" {
		d.Version = ""
	}
	return d, nil
}

func read(path string, withSum bool) (*File, []LockEntry, error) {
	fh, err := os.Open(path)
	if err != nil {
		return nil, nil, err
	}
	defer fh.Close()
	f := &File{}
	var locks []LockEntry
	lang := ""
	sc := bufio.NewScanner(fh)
	n := 0
	for sc.Scan() {
		n++
		line := cut(sc.Text())
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			lang = strings.ToLower(strings.TrimSpace(line[1 : len(line)-1]))
			if !proto.DepLangRe.MatchString(lang) {
				return nil, nil, fmt.Errorf("%s:%d: invalid language section %q", path, n, line)
			}
			continue
		}
		if i := strings.Index(line, "="); i > 0 {
			key := strings.ToLower(strings.TrimSpace(line[:i]))
			val := strings.Trim(strings.TrimSpace(line[i+1:]), `"`)
			if key == "server" && lang == "" {
				f.Server = strings.TrimRight(val, "/")
				continue
			}
			return nil, nil, fmt.Errorf("%s:%d: unknown setting %q", path, n, key)
		}
		if lang == "" {
			return nil, nil, fmt.Errorf("%s:%d: dependency before any [language] section", path, n)
		}
		fields := strings.Fields(line)
		arch := ""
		sum := ""
		if len(fields) > 1 {
			arch = fields[1]
		}
		if len(fields) > 2 {
			if !withSum || !strings.HasPrefix(fields[2], "sha256:") {
				return nil, nil, fmt.Errorf("%s:%d: unexpected %q", path, n, fields[2])
			}
			sum = strings.TrimPrefix(fields[2], "sha256:")
		}
		if len(fields) > 3 {
			return nil, nil, fmt.Errorf("%s:%d: too many fields", path, n)
		}
		d, err := ParseDep(lang, fields[0], arch)
		if err != nil {
			return nil, nil, fmt.Errorf("%s:%d: %w", path, n, err)
		}
		if withSum {
			locks = append(locks, LockEntry{d, sum})
		} else {
			f.Deps = append(f.Deps, d)
		}
	}
	return f, locks, sc.Err()
}

func Parse(path string) (*File, error) {
	f, _, err := read(path, false)
	return f, err
}

func ParseLock(path string) (*Lock, error) {
	_, entries, err := read(path, true)
	if err != nil {
		return nil, err
	}
	return &Lock{Entries: entries}, nil
}

func (l *Lock) Find(d Dep) *LockEntry {
	if l == nil {
		return nil
	}
	for i := range l.Entries {
		e := &l.Entries[i]
		if e.Lang == d.Lang && e.Name == d.Name && e.Arch == d.Arch && (d.Version == "" || e.Version == d.Version) {
			return e
		}
	}
	return nil
}

func (l *Lock) Set(e LockEntry) {
	for i := range l.Entries {
		x := &l.Entries[i]
		if x.Lang == e.Lang && x.Name == e.Name && x.Arch == e.Arch {
			l.Entries[i] = e
			return
		}
	}
	l.Entries = append(l.Entries, e)
}

func (l *Lock) Save(path string) error {
	sort.Slice(l.Entries, func(i, j int) bool {
		a, b := l.Entries[i], l.Entries[j]
		if a.Lang != b.Lang {
			return a.Lang < b.Lang
		}
		if a.Name != b.Name {
			return a.Name < b.Name
		}
		return a.Arch < b.Arch
	})
	var sb strings.Builder
	sb.WriteString("# generated by nekpo, do not edit\n")
	cur := ""
	for _, e := range l.Entries {
		if e.Lang != cur {
			if cur != "" {
				sb.WriteString("\n")
			}
			cur = e.Lang
			fmt.Fprintf(&sb, "[%s]\n", cur)
		}
		fmt.Fprintf(&sb, "%s:%s %s sha256:%s\n", e.Name, e.Version, e.Arch, e.SHA256)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(sb.String()), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
